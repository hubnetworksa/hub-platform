#!/usr/bin/env node
// Turns the owner's own descriptions into guarded SQL, with the same checks and
// the same guard as to-sql.mjs (shared in lib.mjs).
//   content-upgrade/owner/<city>.json   { "<slug>": "description", ... }  (empty = not written yet)
//   node scripts/content-upgrade/owner-sql.mjs <city>
// Writes db/routine-updates/<city>/owner-<YYYYMMDD-HHMM>.sql, moves the written
// slugs into content-upgrade/owner/<city>.done.json and out of <city>.json so
// they are never emitted twice. Owner text has no source URL; source_urls is untouched.
import { readFileSync, writeFileSync, readdirSync, mkdirSync } from 'node:fs';
import { textErrors, repeatedSentenceErrors, buildGuard, q } from './lib.mjs';

const city = process.argv[2];
if (!['pretoria', 'polokwane', 'capetown'].includes(city)) {
  console.error('Usage: node scripts/content-upgrade/owner-sql.mjs <pretoria|polokwane|capetown>');
  process.exit(2);
}
const ownerFile = `content-upgrade/owner/${city}.json`;
let owner;
try { owner = JSON.parse(readFileSync(ownerFile, 'utf8')); } catch (e) { console.error(`Can't read ${ownerFile}: ${e.message}`); process.exit(1); }

const current = new Map();
for (const f of readdirSync(`content-upgrade/${city}`).filter((f) => /^chunk-\d+\.json$/.test(f))) {
  for (const l of JSON.parse(readFileSync(`content-upgrade/${city}/${f}`, 'utf8')).listings ?? []) current.set(l.slug, l.current_description);
}
const items = Object.entries(owner)
  .map(([slug, d]) => ({ slug, description: typeof d === 'string' ? d.trim() : '' }))
  .filter((i) => i.description);
if (!items.length) { console.log(`nothing to do: no filled descriptions in ${ownerFile}`); process.exit(0); }

const errors = [];
for (const [i, it] of items.entries()) {
  const at = `${it.slug}`;
  if (!current.has(it.slug)) errors.push(`${at}: slug isn't in any ${city} chunk file`);
  errors.push(...textErrors(at, it.description));
}
errors.push(...repeatedSentenceErrors(items));
if (errors.length) {
  console.error(`${errors.length} problem(s) in ${ownerFile} (nothing was written; fix them, then run this again):\n- ${errors.join('\n- ')}`);
  process.exit(1);
}

const d = new Date();
const p2 = (n) => String(n).padStart(2, '0');
const stamp = `${d.getFullYear()}${p2(d.getMonth() + 1)}${p2(d.getDate())}-${p2(d.getHours())}${p2(d.getMinutes())}`;
const sqlFile = `db/routine-updates/${city}/owner-${stamp}.sql`;
const sql = [`-- owner-written:${city}: ${items.length} descriptions, generated by scripts/content-upgrade/owner-sql.mjs`];
for (const it of items) {
  sql.push(`-- ${it.slug} (owner)`,
    `UPDATE businesses SET description = ${q(it.description)}, description_enriched_at = datetime('now') WHERE ${buildGuard(it.slug, current.get(it.slug))};`);
}
mkdirSync(`db/routine-updates/${city}`, { recursive: true });
writeFileSync(sqlFile, sql.join('\n') + '\n');

const doneFile = `content-upgrade/owner/${city}.done.json`;
let done = {};
try { done = JSON.parse(readFileSync(doneFile, 'utf8')); } catch {}
const at = d.toISOString();
for (const it of items) { done[it.slug] = { description: it.description, written_at: at, sql_file: sqlFile }; delete owner[it.slug]; }
writeFileSync(doneFile, JSON.stringify(done, null, 2) + '\n');
writeFileSync(ownerFile, JSON.stringify(owner, null, 2) + '\n');
console.log(`ok: ${sqlFile} (${items.length} owner descriptions)`);
