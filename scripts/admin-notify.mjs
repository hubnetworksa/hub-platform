#!/usr/bin/env node
// Triggers Hub Admin's 5-minute run (admin-app/functions/api/notify/run.ts),
// run every 5 minutes by .github/workflows/admin-notify.yml. Along with the
// call it sends what Hub Admin can't see for itself:
//   - runs: the latest runs of every GitHub workflow (with the failing step
//     and error message of failed ones), for deploy status and alerts
//   - d1:   Cloudflare D1 usage per database per day (rows read / written)
//           and each database's size, for the usage meter and its alerts
//
// The trigger key lives only in Hub Admin's own database (settings
// 'notify_key'): this script creates it there on first use (generated by D1
// itself), reads it with the Cloudflare API and sends it in a header. It is
// never printed, and GitHub masks it in case anything ever echoes it.

const { CLOUDFLARE_API_TOKEN: token, CLOUDFLARE_ACCOUNT_ID: account, ADMIN_URL: adminUrl = 'https://hub-admin-b4x.pages.dev' } = process.env;
if (!token || !account) throw new Error('CLOUDFLARE_API_TOKEN and CLOUDFLARE_ACCOUNT_ID are required.');
const base = `https://api.cloudflare.com/client/v4/accounts/${account}/d1/database`;
const headers = { Authorization: `Bearer ${token}`, 'Content-Type': 'application/json' };

async function cf(url, init) {
  const res = await fetch(url, { ...init, headers });
  const body = await res.json().catch(() => ({}));
  if (!res.ok || body.success === false) throw new Error(`Cloudflare API ${res.status}: ${JSON.stringify(body.errors ?? []).slice(0, 300)}`);
  return body.result;
}

const allDbs = (await cf(`${base}?per_page=100`)) ?? [];
const db = allDbs.find((d) => d.name === 'hub-admin-db');
if (!db) throw new Error('hub-admin-db not found (run the Deploy Hub Admin workflow first).');
const query = (sql, params = []) => cf(`${base}/${db.uuid}/query`, { method: 'POST', body: JSON.stringify({ sql, params }) });

await query(`INSERT OR IGNORE INTO settings (key, value) VALUES ('notify_key', lower(hex(randomblob(32))))`);
const key = (await query(`SELECT value FROM settings WHERE key = 'notify_key'`))?.[0]?.results?.[0]?.value;
if (!key) throw new Error('Could not read the notify key.');
if (process.env.GITHUB_ACTIONS) console.log(`::add-mask::${key}`);

// ── GitHub workflow runs ──
async function githubRuns() {
  const repo = process.env.GITHUB_REPOSITORY;
  const gh = process.env.GITHUB_TOKEN;
  if (!repo || !gh) return undefined;
  const ghHeaders = { Authorization: `Bearer ${gh}`, Accept: 'application/vnd.github+json', 'X-GitHub-Api-Version': '2022-11-28' };
  const getJson = async (path) => {
    const r = await fetch(`https://api.github.com/repos/${repo}${path}`, { headers: ghHeaders });
    if (!r.ok) throw new Error(`GitHub ${r.status} for ${path}`);
    return r.json();
  };
  const { workflows } = await getJson('/actions/workflows?per_page=100');
  const runs = [];
  for (const wf of workflows.filter((w) => w.state === 'active' && w.path !== '.github/workflows/admin-notify.yml')) {
    const { workflow_runs } = await getJson(`/actions/workflows/${wf.id}/runs?per_page=3&exclude_pull_requests=true`);
    workflow_runs.forEach((r, i) => runs.push({ r, latest: i === 0 }));
  }
  const out = [];
  for (const { r, latest } of runs) {
    const run = {
      id: r.id, name: r.name, path: r.path, status: r.status, conclusion: r.conclusion, branch: r.head_branch, event: r.event,
      title: r.display_title, created_at: r.created_at, updated_at: r.updated_at, url: r.html_url, error: null,
    };
    // Where a latest run failed: the failing job, step and first error line.
    if (latest && (r.conclusion === 'failure' || r.conclusion === 'timed_out')) {
      try {
        const { jobs } = await getJson(`/actions/runs/${r.id}/jobs?filter=latest`);
        const job = jobs.find((j) => j.conclusion === 'failure' || j.conclusion === 'timed_out');
        const step = job?.steps?.find((st) => st.conclusion === 'failure' || st.conclusion === 'timed_out');
        let message = '';
        if (job) {
          const notes = await getJson(`/check-runs/${job.id}/annotations`);
          message = (notes.find((a) => a.annotation_level === 'failure') ?? notes[0])?.message ?? '';
        }
        run.error = { job: job?.name ?? '', step: step?.name ?? '', message: message.slice(0, 600) };
      } catch (e) {
        run.error = { job: '', step: '', message: '' };
      }
    }
    out.push(run);
  }
  return out.sort((a, b) => b.created_at.localeCompare(a.created_at));
}

// ── Cloudflare D1 usage (GraphQL analytics) ──
async function d1Usage() {
  const end = new Date();
  const start = new Date(end.getTime() - 13 * 86400000);
  const day = (d) => d.toISOString().slice(0, 10);
  const query = `query($a: String!, $s: Date!, $e: Date!) { viewer { accounts(filter: { accountTag: $a }) {
    d1AnalyticsAdaptiveGroups(limit: 5000, filter: { date_geq: $s, date_leq: $e }) {
      sum { readQueries writeQueries rowsRead rowsWritten } dimensions { date databaseId } } } } }`;
  const res = await fetch('https://api.cloudflare.com/client/v4/graphql', { method: 'POST', headers, body: JSON.stringify({ query, variables: { a: account, s: day(start), e: day(end) } }) });
  const body = await res.json().catch(() => ({}));
  if (!res.ok || body.errors?.length) {
    const msg = body.errors?.[0]?.message ?? `HTTP ${res.status}`;
    return { error: /auth|permission|access/i.test(msg) ? 'The Cloudflare API token can’t read analytics (needs “Account Analytics: Read”).' : `Cloudflare analytics: ${msg}` };
  }
  const names = Object.fromEntries(allDbs.map((d) => [d.uuid, d.name]));
  const sizes = Object.fromEntries(allDbs.map((d) => [d.name, d.file_size ?? null]));
  const groups = body.data?.viewer?.accounts?.[0]?.d1AnalyticsAdaptiveGroups ?? [];
  const usage = groups.map((g) => {
    const name = names[g.dimensions.databaseId] ?? g.dimensions.databaseId;
    return { day: g.dimensions.date, database: name, rows_read: g.sum.rowsRead, rows_written: g.sum.rowsWritten, read_queries: g.sum.readQueries, write_queries: g.sum.writeQueries, size_bytes: g.dimensions.date === day(end) ? sizes[name] : null };
  });
  return { usage };
}

const extra = {};
try {
  extra.runs = await githubRuns();
} catch (e) {
  console.log(`GitHub runs not sent: ${e.message}`);
}
try {
  extra.d1 = await d1Usage();
} catch (e) {
  console.log(`D1 usage not sent: ${e.message}`);
}

const res = await fetch(`${adminUrl}/api/notify/run`, { method: 'POST', headers: { 'X-Hub-Admin': '1', 'X-Notify-Key': key, 'Content-Type': 'application/json' }, body: JSON.stringify(extra) });
const out = await res.json().catch(() => ({}));
if (!res.ok) throw new Error(`Hub Admin returned ${res.status}`);
console.log(`New items: ${out.newItems}. Devices notified: ${out.sent}. Runs sent: ${extra.runs?.length ?? 0}. D1: ${extra.d1?.error ?? `${extra.d1?.usage?.length ?? 0} rows`}.`);
// A failed part (e.g. one site's queue) is logged, not fatal: the next run in
// 5 minutes tries again, and failing here would email the owner every time.
for (const e of out.errors ?? []) console.log(`::warning::${e}`);
