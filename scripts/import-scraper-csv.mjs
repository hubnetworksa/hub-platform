// suburb_searched,name,category,address,phone,website,latitude,longitude,
// google_cid,maps_url). The underlying facts were scraped from Google Maps,
// which ROUTINE.md and the businesses.source_urls schema comment both say
// not to do — imported anyway per explicit owner decision, but google_cid
// and maps_url are dropped and never written as source_urls (never a
// Google Maps/Places URL, per schema comment). Where a row has its own
// website that becomes the source; otherwise a non-URL marker is stored so
// the true provenance stays honest and auditable.
//
// Free-text categories are mapped to our fixed taxonomy via exact-match
// lookup only (mirrors scripts/import-osm-businesses.mjs) — anything not
// in the map is skipped rather than force-fit, including B2B/industrial/
// wholesale categories and non-business rows (housing estates, malls,
// corporate offices) that don't belong in a consumer business directory.
//
// Usage: node scripts/import-scraper-csv.mjs --file=<path-to-csv> [--out=path]

